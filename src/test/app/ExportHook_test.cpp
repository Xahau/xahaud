/** xport(): a hook exporting a transaction for the other network. The
    ttEXPORT it emits is checked as far as its preclaim, which wants the
    account's signer list there; Export_test covers the rest. */
class ExportHook_test : public beast::unit_test::suite
{
    int hookAccounts_ = 0;

    // Negative Hook return codes are recorded as 0x8000000000000000 + |code|.
    static std::uint64_t
    rc(hook_api::hook_return_code code)
    {
        return 0x8000000000000000ULL +
            static_cast<std::uint64_t>(-static_cast<std::int64_t>(code));
    }

    static std::vector<std::uint64_t>
    returnCodes(std::shared_ptr<STObject const> const& meta)
    {
        std::vector<std::uint64_t> codes;
        if (meta && meta->isFieldPresent(sfHookExecutions))
            for (auto const& exec : meta->getFieldArray(sfHookExecutions))
                codes.push_back(exec.getFieldU64(sfHookReturnCode));
        return codes;
    }

    // Install a Hook on a fresh account, pay it, and return the account and
    // the payment's metadata. The account holds a few tickets on the other
    // network (as Imports of its TicketCreates would have recorded) unless
    // told otherwise, since an export needs one.
    std::pair<jtx::Account, std::shared_ptr<STObject const>>
    runHook(
        jtx::Env& env,
        jtx::Account const& payer,
        std::vector<std::uint8_t> const& wasm,
        bool tickets = true)
    {
        using namespace jtx;
        Account const account{"hook" + std::to_string(++hookAccounts_)};
        env.fund(XRP(10000), account);
        env.close();
        if (tickets)
        {
            env.app().openLedger().modify([&](OpenView& view, beast::Journal) {
                auto sle = std::make_shared<SLE>(
                    *view.read(keylet::account(account.id())));
                ExportTickets pool;
                pool.add(100, 5);
                pool.store(*sle);
                view.rawReplace(sle);
                return true;
            });
            env.close();
        }
        env(hook(account, {{hso(wasm)}}, 0), fee(XRP(100)));
        env.close();
        env(pay(payer, account, XRP(1)), fee(XRP(1)));
        env.close();
        return {account, env.meta()};
    }

    void
    testXport()
    {
        testcase("xport");
        using namespace jtx;
        using enum hook_api::hook_return_code;

        Env env{*this, supported_amendments() | featureExport};
        Account const bob{"bob"};
        env.fund(XRP(10000), bob);
        env.close();

        // the export is emitted, from the hook's account, unsigned
        {
            auto const [account, meta] = runHook(env, bob, xportWasm);
            BEAST_EXPECT(returnCodes(meta) == std::vector<std::uint64_t>{32});
            if (!BEAST_EXPECT(meta && meta->isFieldPresent(sfHookEmissions)))
                return;
            auto const& emissions = meta->getFieldArray(sfHookEmissions);
            if (!BEAST_EXPECT(emissions.size() == 1))
                return;
            auto const id = emissions[0].getFieldH256(sfEmittedTxnID);

            // it lands in the next ledger, and stops at preclaim: the
            // account has no signer list on the other network
            env.close();
            Json::Value params;
            params[jss::transaction] = to_string(id);
            auto const r =
                env.rpc("json", "tx", to_string(params))[jss::result];
            BEAST_EXPECT(r[jss::TransactionType] == "Export");
            BEAST_EXPECT(r[jss::Account] == account.human());
            BEAST_EXPECT(
                r[sfExportedTxn.jsonName][jss::TransactionType] == "Payment");
            BEAST_EXPECT(
                r[sfExportedTxn.jsonName][jss::Account] == account.human());
            BEAST_EXPECT(r[sfExportedTxn.jsonName][jss::SigningPubKey] == "");
            // bound back here by xport(); the ticket is drawn when it applies
            BEAST_EXPECT(
                r[sfExportedTxn.jsonName][sfOperationLimit.jsonName] ==
                env.app().config().NETWORK_ID);
            BEAST_EXPECT(
                !r[sfExportedTxn.jsonName].isMember(sfTicketSequence.jsonName));
            BEAST_EXPECT(
                r[jss::meta][sfTransactionResult.jsonName] == "tecNO_TARGET");
        }

        // the API's own checks
        BEAST_EXPECT(
            returnCodes(runHook(env, bob, xportWasm, false).second) ==
            std::vector<std::uint64_t>{rc(NO_TICKET)});
        BEAST_EXPECT(
            returnCodes(runHook(env, bob, xportSmallWasm).second) ==
            std::vector<std::uint64_t>{rc(TOO_SMALL)});
        BEAST_EXPECT(
            returnCodes(runHook(env, bob, xportBoundsWasm).second) ==
            std::vector<std::uint64_t>{rc(OUT_OF_BOUNDS)});
        BEAST_EXPECT(
            returnCodes(runHook(env, bob, xportBadWasm).second) ==
            std::vector<std::uint64_t>{rc(INVALID_ARGUMENT)});
        BEAST_EXPECT(
            returnCodes(runHook(env, bob, xportNoReserveWasm).second) ==
            std::vector<std::uint64_t>{rc(PREREQUISITE_NOT_MET)});
    }

    void
    testDisabled()
    {
        testcase("xport disabled");
        using namespace jtx;

        Env env{*this, supported_amendments() - featureExport};
        Account const alice{"alice"};
        env.fund(XRP(10000), alice);
        env.close();

        // the API is not available to SetHook
        env(hook(alice, {{hso(xportWasm)}}, 0),
            fee(XRP(100)),
            ter(temMALFORMED));
    }

public:
    void
    run() override
    {
        testXport();
        testDisabled();
    }
};

BEAST_DEFINE_TESTSUITE(ExportHook, app, ripple);

